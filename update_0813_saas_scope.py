def set_text(paragraph, text):
    paragraph.text = text


def set_cell(cell, text):
    cell.text = text


def replace_paragraph_start(doc, start, text):
    for paragraph in doc.paragraphs:
        if paragraph.text.strip().startswith(start):
            set_text(paragraph, text)
            return True
    raise ValueError(f"Paragraph starting with {start!r} not found")


def replace_table_cell_contains(doc, contains, text):
    changed = 0
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                if contains in cell.text:
                    set_cell(cell, text)
                    changed += 1
    if changed == 0:
        raise ValueError(f"Cell containing {contains!r} not found")
    return changed


