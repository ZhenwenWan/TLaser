def set_run_font(run, size=10.5, bold=False):
    run.font.name = "SimSun"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    run._element.rPr.rFonts.set(qn("w:ascii"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:hAnsi"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold


def clear_paragraph(p):
    for r in list(p.runs):
        p._p.remove(r._r)


def set_paragraph_text(p, text, size=10.5, bold=False):
    clear_paragraph(p)
    for i, part in enumerate(text.split("\n")):
        if i:
            p.add_run().add_break()
        run = p.add_run(part)
        set_run_font(run, size=size, bold=bold)
    p.paragraph_format.first_line_indent = None
    p.paragraph_format.line_spacing = 1.15


def set_cell_text(cell, text, size=10.5, bold=False, align=None):
    cell.text = ""
    p = cell.paragraphs[0]
    set_paragraph_text(p, text, size=size, bold=bold)
    if align is not None:
        p.alignment = align
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_mar = tc_pr.first_child_found_in("w:tcMar")
    if tc_mar is None:
        tc_mar = OxmlElement("w:tcMar")
        tc_pr.append(tc_mar)
    for side in ("top", "left", "bottom", "right"):
        node = tc_mar.find(qn(f"w:{side}"))
        if node is None:
            node = OxmlElement(f"w:{side}")
            tc_mar.append(node)
        node.set(qn("w:w"), "100")
        node.set(qn("w:type"), "dxa")


def insert_after(paragraph, texts, style=None, size=10.5):
    anchor = paragraph
    for text in texts:
        new_p = deepcopy(paragraph._p)
        paragraph._p.addnext(new_p)
        p = paragraph._parent.paragraphs[paragraph._parent.paragraphs.index(paragraph) + 1]
        clear_paragraph(p)
        if style:
            p.style = style
        set_paragraph_text(p, text, size=size)
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.first_line_indent = Pt(21)
        anchor = p
        paragraph = p
    return anchor


def replace_exact_paragraph(doc, exact, text, size=10.5):
    for p in doc.paragraphs:
        if p.text.strip() == exact:
            set_paragraph_text(p, text, size=size)
            return True
    return False


def find_para(doc, exact):
    for p in doc.paragraphs:
        if p.text.strip() == exact:
            return p
    raise ValueError(f"paragraph not found: {exact}")


